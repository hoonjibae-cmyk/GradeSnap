/**
 * **동시에 하되, 한꺼번에 다는 아니게.**
 *
 * 답안지 한 장의 쪽들을 읽는 일은 서로 아무 상관이 없습니다. 앞쪽을 다
 * 읽어야 뒷쪽을 시작할 이유가 없는데 지금까지 차례로 기다렸습니다 —
 * 시범 운용에서 가장 많이 나온 의견이 "채점이 느리다"였고, 그 시간의
 * 대부분이 여기였습니다(docs/13 §13.47).
 *
 * 동시에 보내면 **가장 오래 걸리는 한 쪽 시간**으로 끝납니다. 보내는
 * 내용도 받는 내용도 똑같고 순서만 바뀌므로 **채점 품질에는 영향이
 * 없습니다.**
 *
 * ---
 *
 * ## 그런데 왜 `Promise.all`이 아닌가
 *
 * 무제한으로 던지면 두 가지가 겹칩니다.
 *
 *   - 브라우저가 이미 답안지 **4장을 동시에** 돌립니다(`LANES`).
 *   - 한 장이 8쪽이면 4×8 = **32개 요청이 한꺼번에** 나갑니다.
 *
 * 그러면 429(너무 잦음)를 맞고, 빨라지기는커녕 채점이 실패합니다.
 * 뚜껑을 씌우면 흔한 경우(1~2쪽)는 어차피 전부 동시이고, 드문 장수만
 * 나눠 나갑니다 — **얻을 것은 다 얻고 사고만 막습니다.**
 *
 * ## 순서는 그대로 돌려줍니다
 *
 * `mergeTranscripts`는 문항 번호로 합치므로 순서에 안 기대지만, 머리말을
 * 고를 때 **먼저 온 쪽**을 봅니다. 들어간 차례대로 돌려주면 이 함수를
 * 넣기 전과 결과가 **한 글자도 안 바뀝니다.** 빨라지는 것 말고는 아무것도
 * 바뀌지 않는 것이 이 변경의 조건이었습니다.
 */

/**
 * `items`를 최대 `limit`개씩 동시에 처리합니다. **결과는 입력 순서대로.**
 *
 * 하나라도 실패하면 그대로 던집니다(`Promise.all`과 같습니다). 이미 나간
 * 요청은 취소할 수 없어 끝까지 가지만, 결과는 버려집니다 — 차례로 돌 때는
 * 앞이 실패하면 뒤를 안 보냈으니 그만큼 돈이 더 나갈 수 있습니다.
 * 실패는 드물고, 매번 몇십 초를 버는 쪽이 낫습니다.
 */
export async function mapLimit<T, R>(
  items: readonly T[],
  limit: number,
  fn: (item: T, index: number) => Promise<R>,
): Promise<R[]> {
  const n = items.length;
  if (n === 0) return [];
  const width = Math.max(1, Math.min(Math.floor(limit) || 1, n));

  const out = new Array<R>(n);
  let next = 0;

  // 일꾼 `width`명이 같은 줄에서 다음 번호를 하나씩 집어 갑니다.
  // 쪽마다 걸리는 시간이 달라도 빈 일꾼이 안 놉니다.
  async function worker(): Promise<void> {
    for (;;) {
      const i = next++;
      if (i >= n) return;
      out[i] = await fn(items[i], i);
    }
  }

  await Promise.all(Array.from({ length: width }, worker));
  return out;
}

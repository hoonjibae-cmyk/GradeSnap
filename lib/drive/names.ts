/**
 * 구글 폴더에서 **어느 파일이 정답지인가**.
 *
 * 폴더에는 정답지와 시험지가 섞여 올라옵니다. 그리고 선생님마다 이름
 * 짓는 방식이 전혀 다릅니다 — 실제로 올라와 있는 것들입니다:
 *
 *   `08040805워드마스터unit33-34 단어 답지.pdf`
 *   `0827_M9(A,B)_Day1-3_재시_답지.pdf`
 *   `0831,0901,0903,0904_5과 본문암기 Test (1차)_답지.pdf`
 *   `8월27일(28일) 목(금)_미사고2_교과서 3과 어휘 test 답지_커트 -10(오답필수)_김은진T.pdf`
 *   `0827,0831_하남고1_2과 본문3,4_내용_답지.pdf`
 *
 * 날짜 적는 법도, 구분 기호도, 순서도 제각각입니다. **공통된 것은 「답지」
 * 두 글자뿐**이고, 그래서 그것만 봅니다. 규칙을 더 얹으면 어느 선생님의
 * 파일이 통째로 안 보이게 됩니다.
 *
 * 시험지 파일에는 「답지」가 안 들어갑니다(`…시험지.pdf`). 「답안지」도
 * 안 걸립니다 — 사이에 「안」이 껴 있어 「답지」를 품지 않습니다.
 */

const KEY_TOKEN = "답지";

/**
 * 「답지」가 들어 있지만 정답지가 아닌 것들.
 *
 * 짧게 유지합니다. 여기에 뭘 넣을 때마다 **누군가의 정답지가 안 보이게 될
 * 위험**이 같이 커집니다. 화면이 목록을 보여주고 사람이 고르는 구조라,
 * 애매하면 걸러 내기보다 보여주는 편이 낫습니다.
 */
const DENY = ["오답노트", "오답 노트"];

/** PDF만 받습니다. 한글·워드 파일은 글자를 못 뽑습니다. */
export const PDF = "application/pdf";

export function isAnswerKeyName(name: string): boolean {
  const n = (name ?? "").normalize("NFKC");
  if (!n.includes(KEY_TOKEN)) return false;
  return !DENY.some((d) => n.includes(d));
}

/**
 * 파일 이름에서 시험 제목을 뽑습니다. **머리글을 못 읽었을 때만 씁니다.**
 *
 * PDF 안에 인쇄된 머리글이 훨씬 낫습니다 — 학생 답안지에 찍힌 것과 같은
 * 글자니까요. 파일 이름은 선생님이 자기 편하려고 지은 것이라 답안지와
 * 같을 이유가 없습니다. 그래도 아무것도 없는 것보다는 낫고, 무엇보다
 * **사람이 화면에서 고쳐 적을 출발점**이 됩니다.
 */
export function titleFromName(name: string): string {
  return (name ?? "")
    .normalize("NFKC")
    .replace(/\.[a-z0-9]+$/i, "") // 확장자
    .replace(/답지/g, " ")
    .replace(/\S*T\s*$/, "") // 끝에 붙는 선생님 이름 — '김은진T'
    .replace(/[_,]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

-- 실험에 **사진 해상도** 축을 더합니다.
--
-- 2026-08-11 실측에서 사진이 비용의 25%였고, 보낸 그대로 청구된다는 것도
-- 확인됐습니다 — 쪽당 6,376토큰 ≈ 4.78M픽셀 ≈ 2576×1822(docs/13 §13.24).
-- 토큰은 넓이에 붙으므로 긴 변만 줄여도 크게 떨어집니다.
--
--   긴 변 2576 → 1800   사진 토큰 0.49배   월 29만원
--   긴 변 2576 → 1288   사진 토큰 0.25배   월 43만원
--
-- 🔴 다만 `MAX_EDGE`를 2576으로 잡은 이유가 **답안 한 칸이 40~80px**이
-- 되게 하려는 것이었습니다. 줄이면 연필이 안 읽힐 수 있습니다. 모델과
-- 출력 형식을 재던 방식 그대로 재고 나서 바꿉니다.
--
-- `null`은 원본 그대로입니다. 지금까지 쌓인 실험 기록이 전부 그것입니다.

alter table public.model_trials
  add column if not exists edge int;

-- 아는 값만. 아무 숫자나 받으면 비교가 흩어져 아무것도 못 배웁니다.
alter table public.model_trials
  add constraint model_trials_edge_known
  check (edge is null or edge in (2576, 2000, 1800, 1568, 1288));
